// T10-37 — 사진을 화면 안에서 보여 주려면 **무엇으로 검색하느냐**가 전부다 (결정 #63).
//
// 실제 저장된 장소로 재 봤다 (2026-08-21, 네이버 이미지 검색):
//   "수영구 춘식이네"  → 춘식이네 **건강즙 상품** 사진   ✗
//   "부산 춘식이네"    → "유명한곳 춘식이네를 다녀왔어요"  ✓
//   "남구 보그호프"    → 대구 남구 뉴스                  ✗
//   "부산 보그호프"    → "부산 대연동 보그호프 #미슐랭맛집" ✓
//   "부산 남구 보그호프 맛집" → 다이닝코드의 **다른 가게** 목록 ✗
// 즉 지도 링크는 구(區)가 낫고 이미지 검색은 시(市)가 낫다 — 블로그가 "부산 보그호프"라 쓰기 때문이다.

import { describe, expect, it } from 'vitest'
import { cityOf, imageQueryOf } from './image-query'

describe('cityOf — 주소 첫 토막을 짧게', () => {
  it('광역시는 이름만 남긴다', () => {
    expect(cityOf('부산광역시 남구 대연동 1')).toBe('부산')
  })

  it('특별자치도도 이름만 남긴다', () => {
    expect(cityOf('제주특별자치도 서귀포시 성산읍 1')).toBe('제주')
  })

  it('도는 이름만 남긴다', () => {
    expect(cityOf('경기도 수원시 팔달구 1')).toBe('경기')
  })

  it('주소가 없으면 빈 문자열이다', () => {
    expect(cityOf('')).toBe('')
  })
})

describe('imageQueryOf — 시(市) + 이름', () => {
  it('시를 앞에 붙인다 — 구를 붙이면 엉뚱한 상품 사진이 나온다 (실측)', () => {
    expect(imageQueryOf('춘식이네', '부산광역시 수영구 황령대로489번길 10')).toBe('부산 춘식이네')
  })

  it('이름에 이미 지역이 있으면 겹쳐 붙이지 않는다 — "부산 부산 기장시장" 이 된다 (실측)', () => {
    expect(imageQueryOf('부산 기장시장', '부산광역시 기장군 기장읍 대라리 72-3')).toBe(
      '부산 기장시장',
    )
  })

  it('주소가 없으면 이름만으로 찾는다', () => {
    expect(imageQueryOf('이름만있는곳', '')).toBe('이름만있는곳')
  })

  it('앞뒤 공백은 정리한다 — 캐시 키가 갈라지면 같은 검색을 두 번 산다', () => {
    expect(imageQueryOf('  보그호프  ', '부산광역시 남구 수영로196번길 18')).toBe('부산 보그호프')
  })
})
