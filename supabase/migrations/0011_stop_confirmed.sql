-- 결정 #47 — 일차 안의 방문에 **확정/미확정**을 둔다. 경로는 확정된 것만 잇는다.
--
-- 별표(#46)로 협의가 끝난 곳과 아직 이야기 중인 곳이 한 일차에 섞인다.
-- 둘을 다 이어 경로를 내면 "아직 갈지 모르는 곳"까지 낀 시간이 나와 계획이 흔들린다.
--
-- **기본값이 true 인 이유**: 일차에 넣는 행위 자체가 이미 "가기로 했다"는 뜻이다.
-- false 로 두면 ① 이미 있는 여행들의 경로가 전부 사라지고 ② 장소를 담을 때마다
-- 확정 체크를 한 번 더 눌러야 해서, 한 번이면 될 일이 두 번이 된다.
-- 아직 고민 중인 것만 체크를 풀게 한다 — 예외를 표시하는 쪽이 짧다.
--
-- 표(#46)와 달리 이건 **주인의 판단**이다. 별표는 의견을 모으고, 확정은 주인이 정한다 —
-- 표가 임계값을 넘으면 자동 확정되게 하지 않은 이유는, 그러면 동행자가 별을 누를 때마다
-- 경로가 저 혼자 바뀌고 화면이 왜 바뀌었는지 아무도 설명하지 못하기 때문이다.

alter table public.stops
  add column confirmed boolean not null default true;
