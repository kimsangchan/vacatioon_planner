--
-- 결정 #24 를 뒤집는 것이 아니다. #24 가 places.cost_amount 를 거부한 이유는 두 가지였다:
-- ① 같은 장소를 두 번 가면 지출이 각각이라 장소에는 담을 수 없다 ② 보관함 단계의 가격은
-- 확정 전 추정치다. ①은 여전히 옳다 — 그래서 **실제 지출은 stops.cost_amount 에 그대로 둔다**.
-- ②는 "그러니 적지 말자"가 아니라 "추정치로서 적자"가 사용자의 요구였다("식당 예상 금액을
-- 저장해 경비 계산에 쓰고 싶다"). 추정 단가는 방문이 아니라 **장소의 성질**이라 Place 에 붙는다.
--
-- 두 컬럼은 서로를 채우지 않는다. 자동 복사(예상 → 실제)는 넣지 않는다 — 한 번 복사되는 순간
-- 화면에서 "적어 둔 값"과 "정말 쓴 값"을 구분할 수 없게 되고, 그게 이 기능의 존재 이유다.
--
-- 어휘·제약은 legs.cost_amount(#17)·stops.cost_amount(#24)와 한 글자도 다르지 않게 맞춘다 —
-- 원 단위 정수, 음수 금지, 기본값 없음(미입력 null 과 0원은 다른 값).
--
-- RLS 는 손대지 않는다: places 정책(0002)은 행 단위라 새 컬럼에 그대로 적용된다.

